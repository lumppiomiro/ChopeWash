import assert from "node:assert/strict";
import { bookingCalendarEvents, calendarFile, googleCalendarUrl } from "../src/lib/booking-calendar.ts";

const wash = { id: "w1", kind: "wash", dateLabel: "31 Oct", dateIso: "2026-10-31", startTime: "23:30", duration: 30, status: "confirmed", pairId: "plan" };
const dryer = { ...wash, id: "d1", kind: "dry", dateIso: "2026-11-01", startTime: "00:15", duration: 60 };
const events = bookingCalendarEvents([wash, { ...wash, id: "w2" }, dryer]);
assert.equal(events.length, 3);
assert.equal(new Set(events.map(e => e.id)).size, 3);
assert.equal(events[0].startsAt, "2026-10-31T15:30:00.000Z");
assert.equal(events[1].startsAt, events[0].startsAt);
assert.equal(events[2].endsAt, "2026-10-31T17:15:00.000Z");
assert.match(events[1].title, /Washer 2/);
assert.equal(bookingCalendarEvents([{ ...wash, status: "cancelled" }, { ...dryer, status: "missed" }]).length, 0);
assert.equal(bookingCalendarEvents([{ ...wash, startTime: "invalid" }]).length, 0);
assert.equal(bookingCalendarEvents([{ ...wash, status: "complete" }]).length, 1); // retained earlier stage
const running = bookingCalendarEvents([{ ...wash, status: "checked-in", startedAt: "2026-10-31T23:42:00+08:00", machineName: "Washer 01" }])[0];
assert.equal(running.startsAt, "2026-10-31T15:42:00.000Z");
assert.match(running.title, /Washer 01/);
const staggered = bookingCalendarEvents([wash, { ...wash, id: "w2", startTime: "23:45" }]);
assert.notEqual(staggered[0].startsAt, staggered[1].startsAt);
const queue = { id: "plan", kind: "washer", quantity: 2, status: "claimed", startedAt: "2026-10-31T23:30:00+08:00", machineIds: ["m1", "m2"] };
assert.equal(bookingCalendarEvents([dryer], queue, [{ id: "m1", name: "Washer 01" }]).length, 3);
assert.equal(bookingCalendarEvents([dryer], { ...queue, status: "offered" }).length, 1);
const exportedAt = "2026-10-13T00:00:00Z";
const ics = calendarFile(events, exportedAt);
assert.equal(ics.match(/BEGIN:VEVENT/g).length, 3);
assert.equal(ics.match(/BEGIN:VALARM/g).length, 3);
assert.match(ics, /DTSTART:20261031T153000Z/);
assert.match(ics, /DTEND:20261031T171500Z/);
assert.ok(ics.startsWith("BEGIN:VCALENDAR\r\n"));
assert.ok(ics.endsWith("END:VCALENDAR\r\n"));
assert.equal(calendarFile([running], "2026-10-31T16:00:00Z").includes("VALARM"), false);
const hostile = { ...events[0], title: "Laundry, dry; \\ test\r\nBEGIN:VEVENT " + "🧺".repeat(60), description: "Hello\nworld" };
const escaped = calendarFile([hostile], exportedAt);
assert.equal(escaped.match(/BEGIN:VEVENT\r\n/g).length, 1);
const unfolded = escaped.replace(/\r\n /g, "");
assert.ok(unfolded.includes("Laundry\\, dry\\; \\\\ test\\nBEGIN:VEVENT"));
assert.ok(unfolded.includes("🧺".repeat(60)));
for (const line of escaped.split("\r\n")) assert.ok(Buffer.byteLength(line) <= 75);
assert.equal(escaped.replace(/\r\n/g, "").includes("\n"), false);
const url = new URL(googleCalendarUrl(events[2]));
assert.equal(url.origin, "https://calendar.google.com");
assert.equal(url.searchParams.get("dates"), "20261031T161500Z/20261031T171500Z");
assert.equal(url.searchParams.get("ctz"), "Asia/Singapore");
assert.equal(new URL(googleCalendarUrl(hostile)).searchParams.get("text"), hostile.title);
console.log("PASS: whole-plan events, simultaneous/staggered machines, queued wash, actual check-in, midnight/time zones, inactive stages, reminders, safe UTF-8 ICS and Google links.");
